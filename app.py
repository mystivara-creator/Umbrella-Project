@app.get("/api/status")
async def status() -> dict[str, Any]:
    source_manifest = json.loads(
        (ROOT / "config/sources/kernel-source.json").read_text(encoding="utf-8")
    )
    device_baseline = json.loads(
        (ROOT / "config/devices/kunzite-global.json").read_text(encoding="utf-8")
    )
    wf_raw = (ROOT / ".github/workflows/kernel-build.yml").read_text(encoding="utf-8")
    wf_parsed = yaml.safe_load(wf_raw)
    triggers = wf_parsed.get("on") or wf_parsed.get(True) or {}

    gates = [
        run_gate("Foundation Gate", [sys.executable, "tools/validate_foundation.py"]),
        run_gate("Device Baseline Gate", [sys.executable, "tools/validate_device_baseline.py"]),
        run_gate("Source Provenance Gate", [sys.executable, "tools/source_audit.py"]),
        run_gate("Region Compatibility Gate", [sys.executable, "tools/validate_regions.py"]),
        run_gate(
            "Pipeline Unit & YAML Tests",
            [sys.executable, "-m", "unittest", "discover", "-s", "tests", "-p", "test_*.py"],
        ),
    ]

    bundle_manifest = []
    for rel_path in REPO_BUNDLE_FILES:
        fp = ROOT / rel_path
        raw = fp.read_bytes()
        bundle_manifest.append(
            {
                "path": rel_path,
                "bytes": len(raw),
                "lines": len(raw.splitlines()),
                "sha256": sha256_bytes(raw),
            }
        )

    return {
        "all_gates_passed": all(g["passed"] for g in gates),
        "flash_approved": False,
        "git_push_status": "LOCAL_VALIDATED_NOT_PUSHED (no GitHub write token in container; apply via Termux bundle)",
        "device_baseline": device_baseline,
        "source_manifest": source_manifest,
        "remote_audit": {
            "repository": "mystivara-creator/Umbrella-Project",
            "default_branch": "main",
            "remote_head_sha": "e838e38f58c7c53eb1a669ca1e3828ab8cbfaff8",
            "workflow_id": 400913716,
            "workflow_state_observed": "active (0 prior runs)",
            "stock_config_in_remote_git": False,
            "root_causes": [
                "Remote kernel-build.yml (commit e838e38) only declared bare `on: workflow_dispatch:` with null inputs and lacked `push:` triggers (unlike foundation/source-audit/region-compatibility), resulting in 0 automatic runs.",
                "Remote kernel-build.yml omitted `permissions: contents: read` and could not be triggered from CLI/Termux if PAT lacked `workflow` / `Actions: write` scope.",
                "Legacy 51-line workflow attempted a 19 GB full `repo sync` on a ~14 GB free `ubuntu-24.04` runner, lacked `MiCode/kernel_devicetree`, `MiCode/kernel_build`, `@dtc` (`external/dtc`), `build/BUILD.bazel`, `--define=FACTORY_BUILD=None`, and `--allow_undeclared_modules`.",
            ],
        },
        "workflow_triggers": list(triggers.keys()) if isinstance(triggers, dict) else [],
        "verified_bazel_targets": VERIFIED_BAZEL_TARGETS,
        "gates": gates,
        "bundle_files": bundle_manifest,
    }


