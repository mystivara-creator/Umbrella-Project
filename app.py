def sha256_bytes(payload: bytes) -> str:
    return hashlib.sha256(payload).hexdigest()


def run_gate(name: str, cmd: list[str]) -> dict[str, Any]:
    proc = subprocess.run(
        cmd,
        cwd=str(ROOT),
        stdout=subprocess.PIPE,
        stderr=subprocess.STDOUT,
        text=True,
        check=False,
    )
    return {
        "name": name,
        "command": " ".join(cmd),
        "passed": proc.returncode == 0,
        "exit_code": proc.returncode,
        "output": proc.stdout.strip(),
    }


def build_termux_apply_script() -> str:
    lines = [
        "#!/data/data/com.termux/files/usr/bin/env bash",
        "set -euo pipefail",
        "",
        "# Umbrella Project — Verified Patch Bundle (Phases A–E)",
        "# Touches ONLY Umbrella-Project repository files; never touches AI Studio files.",
        "",
        'REPO_DIR="${1:-$(pwd)}"',
        'cd "$REPO_DIR"',
        "",
        'if [ ! -d ".git" ] || [ ! -f "config/devices/kunzite-global.json" ]; then',
        '  echo "ERROR: Run this script inside your local Umbrella-Project git clone." >&2',
        "  exit 1",
        "fi",
        "",
        'echo "=== Applying 6 SHA-256-verified Umbrella engineering files in $REPO_DIR ==="',
    ]

    for rel_path in REPO_BUNDLE_FILES:
        raw = (ROOT / rel_path).read_bytes()
        digest = sha256_bytes(raw)
        b64 = base64.b64encode(raw).decode("ascii")
        wrapped = "\n".join(b64[i : i + 76] for i in range(0, len(b64), 76))
        parent = str(Path(rel_path).parent)
        if parent != ".":
            lines.append(f'mkdir -p "{parent}"')
        lines.extend(
            [
                f'base64 -d <<\'EOF_B64\' > "{rel_path}"',
                wrapped,
                "EOF_B64",
                f'echo "{digest}  {rel_path}" | sha256sum -c -',
            ]
        )
        if rel_path.startswith("tools/") and rel_path.endswith(".py"):
            lines.append(f'chmod +x "{rel_path}"')

    lines.extend(
        [
            "",
            'echo "=== Running local validation gates & unit tests ==="',
            "python3 tools/validate_foundation.py",
            "python3 tools/validate_device_baseline.py",
            "python3 tools/source_audit.py",
            "python3 tools/validate_regions.py",
            "python3 -m unittest discover -s tests -p 'test_*.py' -v",
            "",
            'echo "=== Git status & diff summary ==="',
            "git status -s",
            "git diff --stat",
            "",
            'echo ""',
            'echo "Ready to commit and push:"',
            'echo "  git add .github/workflows/kernel-build.yml config/sources/kernel-source.json tools/source_audit.py tools/setup_kleaf_workspace.py tools/verify_build_artifacts.py tests/test_build_pipeline.py"',
            'echo "  git commit -m \\"ci(kleaf): pin kunzite mixed-build provenance, Bazel gates, and artifact verifier\\""',
            'echo "  git push origin main"',
            "",
        ]
    )
    return "\n".join(lines)


def build_termux_workspace_overlay_script() -> str:
    return "\n".join(
        [
            "#!/data/data/com.termux/files/usr/bin/env bash",
            "set -euo pipefail",
            "",
            "# Non-destructive overlay for existing Termux workspace (~19 GB preserved).",
            "# Does NOT delete or re-download already-synced AOSP projects in ~/umbrella-workspace/android-kernel.",
            "",
            'UMBRELLA_REPO="${1:-$HOME/Umbrella-Project}"',
            'KLEAF_WS="${2:-$HOME/umbrella-workspace/android-kernel}"',
            'export TMPDIR="${TMPDIR:-$PREFIX/tmp}"',
            'mkdir -p "$TMPDIR"',
            "",
            'if [ ! -d "$KLEAF_WS" ]; then',
            '  echo "ERROR: Existing workspace not found at $KLEAF_WS" >&2',
            "  exit 1",
            "fi",
            "",
            'python3 "$UMBRELLA_REPO/tools/setup_kleaf_workspace.py" \\',
            '  --workspace "$KLEAF_WS" \\',
            "  --reuse-existing \\",
            "  --query-only \\",
            "  --jobs 2",
            "",
            'echo "=== Workspace wired cleanly without re-downloading 19 GB AOSP tree ==="',
            'cat "$KLEAF_WS/workspace-provenance.json"',
            "",
        ]
    )


